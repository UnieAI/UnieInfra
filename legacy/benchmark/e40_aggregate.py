def write_summary_csvs() -> list[str]:
    """Emit results/unieinfra/<label>/summary.csv so trajectory.py sees E40."""
    written = []
    jobs: list[tuple[str, list[dict]]] = []
    for tag in ("nospec", "spec"):
        runs = load_toolcall(tag)
        if runs:
            g = group(runs)
            for (arm, c), rs in g.items():
                jobs.append((f"e40_{tag}_{arm}", rs))
    mt = sorted(glob.glob(os.path.join(UNIE, "e40b", "*.json")))
    mt_runs: dict[str, list[dict]] = {}
    for p in mt:
        with open(p) as f:
            r = json.load(f)
        mt_runs.setdefault(f"e40b_{r['config']['arm']}", []).append(r)

    grouped: dict[str, dict[int, list[dict]]] = {}
    for label, rs in jobs:
        for r in rs:
            grouped.setdefault(label, {}).setdefault(
                r["config"]["max_concurrency"], []
            ).append(r)
    for label, rs in mt_runs.items():
        for r in rs:
            grouped.setdefault(label, {}).setdefault(
                r["config"]["max_concurrency"], []
            ).append(r)

    for label, by_c in grouped.items():
        d = os.path.join(UNIE, label)
        os.makedirs(d, exist_ok=True)
        path = os.path.join(d, "summary.csv")
        with open(path, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=SUMMARY_FIELDS)
            w.writeheader()
            for c in sorted(by_c):
                rs = by_c[c]

                def m(f_):
                    return statistics.median([f_(r) for r in rs])

                mm = rs[0]["metrics"]
                w.writerow(
                    {
                        "engine": "unieinfra",
                        "max_concurrency": c,
                        "num_prompts": rs[0]["config"].get("num_prompts")
                        or rs[0]["config"].get("sessions", 0)
                        * rs[0]["config"].get("turns", 1),
                        "completed": mm.get("completed", mm.get("completed_turns", 0)),
                        "duration": round(m(lambda r: r["metrics"]["duration_s"]), 4),
                        "request_throughput": round(
                            m(lambda r: r["metrics"].get("request_throughput", 0.0)), 4
                        ),
                        "output_throughput": round(
                            m(lambda r: r["metrics"]["output_throughput"]), 4
                        ),
                        "mean_ttft_ms": round(
                            m(lambda r: r["metrics"]["mean_ttft_ms"]), 4
                        ),
                        "p99_ttft_ms": round(
                            m(lambda r: r["metrics"].get("p99_ttft_ms", 0.0)), 4
                        ),
                        "mean_tpot_ms": round(
                            m(lambda r: r["metrics"].get("mean_tpot_ms", 0.0)), 4
                        ),
                        "median_ttft_ms": round(
                            m(lambda r: r["metrics"].get("median_ttft_ms", 0.0)), 4
                        ),
                        "median_tpot_ms": round(
                            m(lambda r: r["metrics"].get("median_tpot_ms", 0.0)), 4
                        ),
                        "mean_itl_ms": round(
                            m(lambda r: r["metrics"].get("mean_itl_ms", 0.0)), 4
                        ),
                        "label": label,
                        "date": "20260725",
                        "total_output_tokens": int(
                            m(lambda r: r["metrics"]["total_output_tokens"])
                        ),
                        "total_input_tokens": int(
                            m(lambda r: r["metrics"].get("total_input_tokens", 0))
                        ),
                    }
                )
        written.append(path)
    return written


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default=DEFAULT_DATA)
    args = ap.parse_args()

    p1 = part1(args.data)
    with open(os.path.join(RESULTS, "E40_TOOLCALL.md"), "w") as f:
        f.write(p1)
    print(p1)

    p2 = part2()
    with open(os.path.join(RESULTS, "E40B_MULTITURN.md"), "w") as f:
        f.write(p2)
    print(p2)

    for p in write_summary_csvs():
        print(f"wrote {p}")


if __name__ == "__main__":
    main()
