def load_toolcall(tag: str) -> list[dict]:
    out = []
    for p in sorted(glob.glob(os.path.join(UNIE, f"e40_{tag}", "*.json"))):
        with open(p) as f:
            out.append(json.load(f))
    return out


def group(runs: list[dict]) -> dict[tuple[str, int], list[dict]]:
    g: dict[tuple[str, int], list[dict]] = {}
    for r in runs:
        g.setdefault((r["config"]["arm"], r["config"]["max_concurrency"]), []).append(r)
    return g


def quality_rows(runs: list[dict], tools_by_id: dict) -> dict[tuple[str, int], dict]:
    out: dict[tuple[str, int], dict] = {}
    for r in runs:
        key = (r["config"]["arm"], r["config"]["max_concurrency"])
        counts: dict[str, int] = {}
        for req in r["requests"]:
            b, _ = classify_one(req, tools_by_id.get(req["request_id"], []))
            counts[b] = counts.get(b, 0) + 1
        judged = sum(counts.values()) - counts.get("failed", 0)
        mal = sum(
            counts.get(k, 0)
            for k in ("parse_fail", "bad_json", "unknown_name", "schema_violation")
        )
        out.setdefault(key, []).append(  # type: ignore[union-attr]
            {"counts": counts, "judged": judged, "malformed": mal}
        )
    return out


def part1(data_path: str) -> str:
    tools_by_id = _load_tools(data_path)
    nospec = load_toolcall("nospec")
    spec = load_toolcall("spec")
    if not nospec:
        return "(no E40 tool-call results found)\n"

    L: list[str] = []
    L.append("<!-- Generated by benchmark/e40_aggregate.py. Do not hand-edit. -->")
    L.append("# E40 — tool-call quality on real BFCL traffic (Qwen3-8B, sm_120)\n")
    L.append(
        "256 frozen BFCL requests (categories `simple`, `live_simple`, `multiple`; "
        "mean 1.44 tools/request), emitted as genuine OpenAI `tools` + "
        "`tool_choice` traffic against `--enable-auto-tool-choice "
        "--tool-call-parser hermes`. Greedy (`temperature 0`), thinking off, "
        "prefix caching off, N=3 repeats with arms rotated back-to-back. "
        "Median `[min, max]`.\n"
    )
    L.append(
        "**Arms differ by exactly one thing:** the `strict` arm sets "
        "`strict: true` on every tool. That is the documented lever — "
        "`vllm/tool_parsers/structural_tag_registry.py:get_model_structural_tag` "
        'returns `None` for `tool_choice="auto"` unless some tool is strict, so '
        "the `auto` arm runs with **no grammar at all** and tool calls are "
        "recovered by regex from raw text.\n"
    )

    for tag, runs in (("nospec", nospec), ("spec", spec)):
        if not runs:
            continue
        q = quality_rows(runs, tools_by_id)
        L.append(
            f"\n## Quality — {'no speculative decoding' if tag == 'nospec' else 'EAGLE3 speculative decoding (k=3)'}\n"
        )
        L.append(
            "| arm | C | judged | ok% | malformed% | parse_fail | bad_json | "
            "unknown_name | schema_viol | no_call |"
        )
        L.append("|" + "---|" * 10)
        for (arm, c), rs in sorted(q.items(), key=lambda kv: (kv[0][1], kv[0][0])):
            j = rs[0]["judged"]

            def m(f):
                return statistics.median([f(x) for x in rs])

            L.append(
                f"| {arm} | {c} | {j} | "
                f"{100 * m(lambda x: x['counts'].get('ok', 0)) / j:.1f} | "
                f"{100 * m(lambda x: x['malformed']) / j:.2f} | "
                f"{m(lambda x: x['counts'].get('parse_fail', 0)):.0f} | "
                f"{m(lambda x: x['counts'].get('bad_json', 0)):.0f} | "
                f"{m(lambda x: x['counts'].get('unknown_name', 0)):.0f} | "
                f"{m(lambda x: x['counts'].get('schema_violation', 0)):.0f} | "
                f"{m(lambda x: x['counts'].get('no_call', 0)):.0f} |"
            )

    # ---- cost of the constraint ----
    L.append("\n## What the structural tag costs\n")
    L.append(
        "| config | C | arm | out tok/s | vs auto | TTFT ms | TPOT ms | mean out len |"
    )
    L.append("|" + "---|" * 8)
    for tag, runs in (("nospec", nospec), ("spec", spec)):
        if not runs:
            continue
        g = group(runs)
        for c in sorted({k[1] for k in g}):
            base = [r["metrics"]["output_throughput"] for r in g[("auto", c)]]
            for arm in ("auto", "strict"):
                rs = g.get((arm, c))
                if not rs:
                    continue
                tp = [r["metrics"]["output_throughput"] for r in rs]
                delta = (
                    "—"
                    if arm == "auto"
                    else (
                        "TIE"
                        if is_tie(tp, base)
                        else pct(statistics.median(tp), statistics.median(base))
                    )
                )
                L.append(
                    f"| {tag} | {c} | {arm} | {cell(tp)} | {delta} | "
                    f"{cell([r['metrics']['mean_ttft_ms'] for r in rs])} | "
                    f"{cell([r['metrics']['mean_tpot_ms'] for r in rs], '{:.2f}')} | "
                    f"{cell([r['metrics']['mean_output_tokens'] for r in rs])} |"
                )

    # ---- grammar x spec 2x2 ----
    if spec:
        L.append("\n## Grammar × speculative decoding (the 2×2)\n")
        L.append(
            "The predicted defect: the draft path applies only "
            "`vocab_mapping.constrain_draft_logits` (vocabulary alignment, **not** "
            "schema), `apply_grammar_bitmask` runs solely on the target side "
            "(`gpu_model_runner.py`), and `validate_tokens` "
            "(`v1/core/sched/scheduler.py:2069`) truncates the spec chain at the "
            "first schema-illegal token. Prediction: acceptance collapses when a "
            "tool/JSON grammar is active.\n"
        )
        L.append(
            "| C | arm | accept len (/4) | accept rate % | draft tok / draft step | "
            "out tok/s |"
        )
        L.append("|" + "---|" * 6)
        gs = group(spec)
        for c in sorted({k[1] for k in gs}):
            for arm in ("auto", "strict"):
                rs = gs.get((arm, c))
                if not rs:
                    continue
                al = [r["spec_decode"]["acceptance_length"] for r in rs]
                ar = [r["spec_decode"]["acceptance_rate"] for r in rs]
                dpd = [
                    r["spec_decode"]["num_draft_tokens"]
                    / r["spec_decode"]["num_drafts"]
                    for r in rs
                ]
                L.append(
                    f"| {c} | {arm} | {cell(al, '{:.3f}')} | {cell(ar, '{:.1f}')} | "
                    f"{cell(dpd, '{:.2f}')} | "
                    f"{cell([r['metrics']['output_throughput'] for r in rs])} |"
                )

        L.append("\n### Speculative-decoding speedup, grammar OFF vs ON\n")
        L.append("| C | arm | no-spec tok/s | spec tok/s | spec speedup |")
        L.append("|" + "---|" * 5)
        gn = group(nospec)
        for c in sorted({k[1] for k in gs}):
            for arm in ("auto", "strict"):
                if (arm, c) not in gn or (arm, c) not in gs:
                    continue
                b = [r["metrics"]["output_throughput"] for r in gn[(arm, c)]]
                s = [r["metrics"]["output_throughput"] for r in gs[(arm, c)]]
                L.append(
                    f"| {c} | {arm} | {cell(b)} | {cell(s)} | "
                    f"{pct(statistics.median(s), statistics.median(b))} |"
                )
    return "\n".join(L) + "\n"


