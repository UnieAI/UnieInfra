def part2() -> str:
    paths = sorted(glob.glob(os.path.join(UNIE, "e40b", "*.json")))
    if not paths:
        return "(no E40b multi-turn results found)\n"
    runs = []
    for p in paths:
        with open(p) as f:
            runs.append(json.load(f))
    by_arm: dict[str, list[dict]] = {}
    for r in runs:
        by_arm.setdefault(r["config"]["arm"], []).append(r)

    cfg = runs[0]["config"]
    L: list[str] = []
    L.append("<!-- Generated by benchmark/e40_aggregate.py. Do not hand-edit. -->")
    L.append("# E40b — genuine multi-turn prefix reuse (conversation growth)\n")
    L.append(
        f"{cfg['sessions']} concurrent sessions x {cfg['turns']} turns, "
        f"C={cfg['max_concurrency']}, {cfg['output_len']} max output tokens, "
        "Qwen3-8B, greedy, thinking off. Within a session turn *k*'s prompt is "
        "`[u1, a1, ..., u_k]` and turns are strictly sequential, so the reusable "
        "prefix grows by a whole turn each round — this is conversation growth, "
        "not prompt repetition. Content: MT-Bench's **full** `turns` list (the "
        "tree's `MTBenchDataset` samples only `turns[0]`); MT-Bench ships 2 turns "
        "per question, so turns 3+ continue the same session with further "
        "questions, which keeps the history growing the way an agent loop does.\n"
    )
    L.append(
        "Arms: `off` = server `--no-enable-prefix-caching`; `cold` = caching on "
        "with `/reset_prefix_cache` immediately before the run (all reuse comes "
        "from within the run itself); `warm` = the same conversations replayed "
        "with no reset. Prefix caching cannot be toggled at runtime, so `off` and "
        "`cold`/`warm` are separate server processes; rep 4 re-runs `off` after "
        "everything else as a drift check.\n"
    )

    L.append("## Totals\n")
    L.append("| arm | reps | out tok/s | vs off | mean TTFT ms | cache hit rate % |")
    L.append("|" + "---|" * 6)
    base_tp = [r["metrics"]["output_throughput"] for r in by_arm.get("off", [])]
    for arm in ("off", "cold", "warm"):
        rs = by_arm.get(arm)
        if not rs:
            continue
        tp = [r["metrics"]["output_throughput"] for r in rs]
        d = (
            "—"
            if arm == "off"
            else (
                "TIE"
                if is_tie(tp, base_tp)
                else pct(statistics.median(tp), statistics.median(base_tp))
            )
        )
        hits = [
            r["prefix_cache"]["hit_rate_pct"] for r in rs if r.get("prefix_cache")
        ] or [0.0]
        L.append(
            f"| {arm} | {len(rs)} | {cell(tp)} | {d} | "
            f"{cell([r['metrics']['mean_ttft_ms'] for r in rs])} | {cell(hits)} |"
        )

    n_turns = cfg["turns"]
    L.append("\n## Per-turn growth — TTFT (ms)\n")
    L.append(
        "| turn | mean prompt tok | off | cold | warm | cold vs off | warm vs off |"
    )
    L.append("|" + "---|" * 7)
    for k in range(n_turns):
        key = str(k)

        def vals(arm, field):
            return [
                r["per_turn"][key][field]
                for r in by_arm.get(arm, [])
                if key in r["per_turn"]
            ]

        off = vals("off", "mean_ttft_ms")
        cold = vals("cold", "mean_ttft_ms")
        warm = vals("warm", "mean_ttft_ms")
        if not off:
            continue
        ptok = statistics.median(vals("off", "mean_prompt_tokens"))
        dc = (
            "TIE"
            if is_tie(cold, off)
            else pct(statistics.median(cold), statistics.median(off))
        )
        dw = (
            "TIE"
            if is_tie(warm, off)
            else pct(statistics.median(warm), statistics.median(off))
        )
        L.append(
            f"| {k} | {ptok:.0f} | {cell(off)} | {cell(cold)} | {cell(warm)} | "
            f"{dc} | {dw} |"
        )

    L.append("\n## Per-turn growth — cached prompt tokens (engine-reported)\n")
    L.append(
        "`prompt_tokens_details.cached_tokens` from the server "
        "(`--enable-prompt-tokens-details`), i.e. how much of turn *k*'s prompt "
        "the engine did not have to prefill.\n"
    )
    L.append(
        "| turn | mean prompt tok | cold cached | cold cached % | warm cached | warm cached % |"
    )
    L.append("|" + "---|" * 6)
    for k in range(n_turns):
        key = str(k)
        rs_cold = [r for r in by_arm.get("cold", []) if key in r["per_turn"]]
        rs_warm = [r for r in by_arm.get("warm", []) if key in r["per_turn"]]
        if not rs_cold:
            continue
        pt = statistics.median(
            [r["per_turn"][key]["mean_prompt_tokens"] for r in rs_cold]
        )
        cc = statistics.median(
            [r["per_turn"][key]["mean_cached_tokens"] or 0.0 for r in rs_cold]
        )
        wc = (
            statistics.median(
                [r["per_turn"][key]["mean_cached_tokens"] or 0.0 for r in rs_warm]
            )
            if rs_warm
            else 0.0
        )
        L.append(
            f"| {k} | {pt:.0f} | {cc:.0f} | {100 * cc / pt if pt else 0:.1f} | "
            f"{wc:.0f} | {100 * wc / pt if pt else 0:.1f} |"
        )

    L.append("\n## Per-turn growth — TPOT (ms)\n")
    L.append("| turn | off | cold | warm |")
    L.append("|" + "---|" * 4)
    for k in range(n_turns):
        key = str(k)

        def vals(arm):
            return [
                r["per_turn"][key]["mean_tpot_ms"]
                for r in by_arm.get(arm, [])
                if key in r["per_turn"]
            ]

        if not vals("off"):
            continue
        L.append(
            f"| {k} | {cell(vals('off'), '{:.2f}')} | "
            f"{cell(vals('cold'), '{:.2f}')} | {cell(vals('warm'), '{:.2f}')} |"
        )
    return "\n".join(L) + "\n"


