"""E40 aggregate — tool-call quality, grammar x spec-decode 2x2, and multi-turn.

Reads the raw run files written by ``benchmark/scripts/e40_toolcall_bench.py``
and ``benchmark/scripts/e40_multiturn_bench.py`` and produces:

  * ``results/E40_TOOLCALL.md``   -- Part 1: malformed/schema-conformance rates,
    what the structural tag costs, and the grammar x speculative-decoding 2x2
    (acceptance length, acceptance rate, draft tokens actually submitted)
  * ``results/E40B_MULTITURN.md`` -- Part 2: per-turn TTFT / TPOT / prompt growth
    / cached-token growth with prefix caching off vs cold vs warm
  * ``results/<engine>/<label>/summary.csv`` rows so ``trajectory.py`` sees E40

Reporting rule (E35 discipline): median of repeats with ``[min, max]`` spread.
A delta that falls inside the spread of either arm is called a TIE.

Usage::

    python3 benchmark/e40_aggregate.py
"""

from __future__ import annotations

import argparse
import csv
import glob
import json
import os
import statistics
import sys
from typing import Any

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "scripts"))
from e40_validate import _load_tools, classify_one  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS = os.path.join(REPO, "benchmark", "results")
UNIE = os.path.join(RESULTS, "unieinfra")
DEFAULT_DATA = "/workspace/roy/bench-data/bfcl_256.jsonl"

SUMMARY_FIELDS = [
    "engine",
    "max_concurrency",
    "num_prompts",
    "completed",
    "duration",
    "request_throughput",
    "output_throughput",
    "mean_ttft_ms",
    "p99_ttft_ms",
    "mean_tpot_ms",
    "median_ttft_ms",
    "median_tpot_ms",
    "mean_itl_ms",
    "label",
    "date",
    "total_output_tokens",
    "total_input_tokens",
]


def med_lo_hi(vals: list[float]) -> tuple[float, float, float]:
    return statistics.median(vals), min(vals), max(vals)


def cell(vals: list[float], fmt: str = "{:.1f}") -> str:
    m, lo, hi = med_lo_hi(vals)
    return f"{fmt.format(m)} [{fmt.format(lo)}, {fmt.format(hi)}]"


def is_tie(a: list[float], b: list[float]) -> bool:
    """True when the two arms' [min, max] ranges overlap."""
    return not (max(a) < min(b) or max(b) < min(a))


def pct(new: float, base: float) -> str:
    if not base:
        return "--"
    d = 100.0 * (new - base) / base
    return f"{d:+.1f}%"


